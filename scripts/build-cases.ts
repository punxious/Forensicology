/**
 * Compiles every case in ./cases into a server-only bundle at
 * lib/server/generated/. Runs automatically before `dev` and `build`.
 *
 *   pnpm case:build            compile all cases
 *   pnpm case:build --check    validate only (no output), exit 1 on errors
 */
import fs from "node:fs";
import path from "node:path";
import nextEnv from "@next/env";
import { compileCase, parseCaseSource, type CaseFiles } from "../lib/engine/compile";
import { getPepper } from "../lib/engine/hash";

const root = path.resolve(import.meta.dirname, "..");
nextEnv.loadEnvConfig(root);

const casesDir = path.join(root, "cases");
const outDir = path.join(root, "lib/server/generated");
const checkOnly = process.argv.includes("--check");

if ((process.env.CI || process.env.VERCEL) && !process.env.ANSWER_PEPPER) {
  console.error("✖ ANSWER_PEPPER is not set. Production builds must use a real pepper.");
  process.exit(1);
}
const pepper = getPepper();

function filesFor(dir: string): CaseFiles {
  const resolve = (rel: string) => {
    const full = path.resolve(dir, rel);
    return full.startsWith(dir + path.sep) && fs.existsSync(full) ? full : null;
  };
  return {
    readText: (rel) => {
      const f = resolve(rel);
      return f ? fs.readFileSync(f, "utf8") : null;
    },
    readBinary: (rel) => {
      const f = resolve(rel);
      return f ? fs.readFileSync(f) : null;
    },
  };
}

const slugs = fs
  .readdirSync(casesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(casesDir, d.name, "case.yaml")))
  .map((d) => d.name)
  .sort();

let failed = false;
const built: string[] = [];
if (!checkOnly) {
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
}

for (const dirName of slugs) {
  const dir = path.join(casesDir, dirName);
  const parsed = parseCaseSource(fs.readFileSync(path.join(dir, "case.yaml"), "utf8"));
  if (!parsed.ok) {
    failed = true;
    console.error(`✖ ${dirName}\n  ${parsed.errors.join("\n  ")}`);
    continue;
  }
  if (parsed.source.slug !== dirName) {
    failed = true;
    console.error(`✖ ${dirName}: slug "${parsed.source.slug}" must match the folder name.`);
    continue;
  }
  const result = compileCase(parsed.source, filesFor(dir), pepper);
  for (const w of result.warnings) console.warn(`  ⚠ ${dirName}: ${w.message}`);
  if (!result.ok) {
    failed = true;
    console.error(`✖ ${dirName}\n  ${result.errors.join("\n  ")}`);
    continue;
  }
  if (!checkOnly) {
    fs.writeFileSync(path.join(outDir, `${dirName}.json`), JSON.stringify(result.compiled));
  }
  built.push(dirName);
  console.log(`✔ ${dirName} (v${result.compiled.version}, ${result.compiled.puzzles.length} puzzles, ${result.compiled.evidence.length} evidence)`);
}

if (!checkOnly) {
  const ident = (s: string) => "c_" + s.replace(/[^a-z0-9]/g, "_");
  const index = [
    "// Generated by scripts/build-cases.ts. Do not edit. Server-only: contains answer hashes.",
    'import "server-only";',
    'import type { CompiledCase } from "@/lib/engine/types";',
    ...built.map((s) => `import ${ident(s)} from "./${s}.json";`),
    "",
    `export const compiledCases: CompiledCase[] = [${built.map((s) => `${ident(s)} as unknown as CompiledCase`).join(", ")}];`,
    "",
  ].join("\n");
  fs.writeFileSync(path.join(outDir, "index.ts"), index);
}

if (failed) process.exit(1);
